import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const bundle = await build({
  entryPoints: [`${root}src/chart-entry.ts`],
  bundle: true,
  write: false,
  minify: true,
  format: "iife",
  target: "es2020",
  legalComments: "inline",
});
const js = bundle.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:;"><style>html,body,#chart{margin:0;width:100%;height:100%;background:#0c100f;overflow:hidden;overscroll-behavior:none}</style></head><body><div id="chart"></div><script>${js}</script></body></html>`;
await writeFile(
  `${root}src/chart-html.ts`,
  "// Generated by npm run chart:bundle. Includes locally bundled Lightweight Charts; see license audit.\nexport const chartHtml = " +
    JSON.stringify(html) +
    ";\n",
);
console.log(`Bundled local chart (${Buffer.byteLength(html)} bytes)`);
